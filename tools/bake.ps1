# Bakes your in-game saves (/ep save) into Baked.lua, so they come along to a new client install
# where EzPersistenceDB starts empty. Run after /ep save on every character you want to keep,
# then log out or /reload so the game writes the saved variables file.
#
# Baked.lua is personal: it's git-ignored and left out of release packages, so only your own
# install loads it.
#
#   powershell -ExecutionPolicy Bypass -File tools\bake.ps1 [-SavedVariables <path to EzPersistence.lua>]
param(
    [string]$SavedVariables
)
$ErrorActionPreference = "Stop"

if (-not $SavedVariables) {
    # Every client folder (_retail_, _classic_, _forever_, ...) under the default install.
    $wow = "C:\Program Files (x86)\World of Warcraft"
    $found = @(Get-ChildItem -Path "$wow\*\WTF\Account" -Filter "EzPersistence.lua" -Recurse -ErrorAction SilentlyContinue |
        Where-Object { $_.Directory.Name -eq "SavedVariables" })
    if ($found.Count -ne 1) {
        $list = ($found | ForEach-Object { "  " + $_.FullName }) -join "`n"
        throw "Found $($found.Count) EzPersistence.lua files under $wow; pass -SavedVariables <path>.`n$list"
    }
    $SavedVariables = $found[0].FullName
}

$source = [IO.File]::ReadAllText($SavedVariables)
if ($source -notmatch "(?m)^EzPersistenceDB = \{") {
    throw "$SavedVariables doesn't look like EzPersistence saved variables."
}

$header = @"
-- EzPersistence: YOUR profiles, baked into your install so they come along to a new client
-- where EzPersistenceDB starts empty. Same shape as EzPersistenceDB; replaces Data.lua's empty table.
-- Generated by tools/bake.ps1 from your saved variables. Personal: git-ignored, never packaged.
local _, ns = ...

"@
$body = ($source -replace "(?m)^EzPersistenceDB = \{", "ns.DATA = {").Trim()

$names = @([regex]::Matches($body, '\["character"\] = "([^"]+)"') | ForEach-Object { $_.Groups[1].Value })
if ($names.Count -eq 0) {
    throw "$SavedVariables has no saved characters; /ep save in game first. Baked.lua left as it was."
}

$out = Join-Path (Split-Path $PSScriptRoot -Parent) "Baked.lua"
[IO.File]::WriteAllText($out, $header + "`n" + $body + "`n", (New-Object Text.UTF8Encoding $false))
Write-Output "Baked $SavedVariables into Baked.lua: $($names -join ', ')"
